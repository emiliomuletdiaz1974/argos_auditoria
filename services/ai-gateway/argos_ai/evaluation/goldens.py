"""Golden sets of the AI layer, maintained by hand (F06-02, ARG-059).

They live beside the harness that measures with them (`argos_ai.evaluation`), because the harness is
product: it gates releases. The test fixtures re-export this module.

Four trades and the guardrails, five suites, one shape. A case is `{id, kind, input, expected,
why}`, where `kind` is `plain` or `trap`: the traps are the cases that measure refusal —the hardest
virtue— and the harness weighs them double.

Nothing here comes from a client: the questions are built on the v1 populations and on the synthetic
record of the Phase 05 campaign. And nothing here is generated by a model: if it were, the sets
would measure the model against itself.
"""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[4]
GOLDENS_DIR = REPO / "goldens"
EDITORIAL_DIR = REPO / "library" / "ontology" / "editorial"
INVENTORY_TRUTH = REPO / "tests" / "fixtures" / "inventory_ground_truth.yaml"
THRESHOLDS_FILE = GOLDENS_DIR / "thresholds.yaml"
SUITES = ("classify", "generate", "rag", "reports", "guardrails")
KINDS = ("plain", "trap")
# The closed vocabulary of the deterministic classifier (ARG-024); the semantic one does not widen
# it: a category the product does not know is not a category.
CATEGORIES = (
    "official_identifier",
    "special_category.health",
    "special_category.other",
    "personal_data",
    "contact_data",
    "financial_data",
    "location_data",
    "technical_credential",
)


class GoldenError(Exception):
    """A golden set that does not hold up as a measuring stick."""


@dataclass(frozen=True, slots=True, order=True)
class Case:
    id: str
    kind: str
    why: str
    input: dict[str, Any]
    expected: dict[str, Any]


@dataclass(frozen=True, slots=True)
class Reference:
    """A citable place of the corpus: `RGPD art. 32.1.a`, with the obligation behind it."""

    obligation: str
    norm: str
    article: str

    @property
    def citation(self) -> str:
        return f"{self.norm} art. {self.article}"


def corpus_references(editorial_dir: Path = EDITORIAL_DIR) -> dict[str, tuple[Reference, ...]]:
    """Citation -> the obligations that live in it.

    A citation is not unique: `RGPD art. 32.1.b` holds both the access log and the encryption in
    transit, and `AIACT art. 6` holds the two classification duties. Keying by citation alone
    would quietly lose half the corpus, so each one keeps every obligation behind it.
    """
    references: dict[str, list[Reference]] = {}
    for path in sorted(editorial_dir.glob("OBL-*.yaml")):
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
        reference = Reference(
            obligation=str(document["id"]),
            norm=str(document["norma"]),
            article=str(document["articulo"]),
        )
        references.setdefault(reference.citation, []).append(reference)
    return {citation: tuple(found) for citation, found in references.items()}


def inventory_columns(path: Path = INVENTORY_TRUTH) -> set[tuple[str, str]]:
    """Every (system, column) the inventory ground truth knows about."""
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    columns: set[tuple[str, str]] = set()
    for system, spec in document["systems"].items():
        for table, names in (spec.get("tables") or {}).items():
            columns.update((system, f"{table}.{name}") for name in names)
    return columns


def load_goldens(suite: str, goldens_dir: Path = GOLDENS_DIR) -> list[Case]:
    """Every case of a suite, sorted by id. A malformed case is an error, never a skip."""
    if suite not in SUITES:
        raise GoldenError(f"unknown suite: {suite!r}")
    directory = goldens_dir / suite
    if not directory.is_dir():
        raise GoldenError(f"the suite {suite} has no directory")
    cases: list[Case] = []
    for path in sorted(directory.glob("*.jsonl")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.strip():
                continue
            cases.append(_case(json.loads(line), f"{path.name}:{number}"))
    return sorted(cases)


def _case(raw: dict[str, Any], where: str) -> Case:
    missing = {"id", "kind", "why", "input", "expected"} - set(raw)
    if missing:
        raise GoldenError(f"{where}: the case is missing {sorted(missing)}")
    if raw["kind"] not in KINDS:
        raise GoldenError(f"{where}: unknown kind {raw['kind']!r}")
    return Case(
        id=str(raw["id"]),
        kind=str(raw["kind"]),
        why=str(raw["why"]),
        input=dict(raw["input"]),
        expected=dict(raw["expected"]),
    )


def load_thresholds(path: Path = THRESHOLDS_FILE) -> dict[str, dict[str, Any]]:
    """The bar of each suite, with the reason it is that number and not another."""
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    thresholds = {str(name): dict(entry) for name, entry in document["thresholds"].items()}
    for name, entry in thresholds.items():
        if "minimum" not in entry or "why" not in entry:
            raise GoldenError(f"the threshold of {name} needs a minimum and its reason")
    return thresholds
